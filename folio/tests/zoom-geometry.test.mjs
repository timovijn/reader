import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('../worker/page.html',import.meta.url),'utf8');
function load(name,next,globals={}){const start=source.indexOf('function '+name+'(');const end=source.indexOf('\nfunction '+next+'(',start);return vm.runInNewContext('('+source.slice(start,end)+')',globals);}
const pageRect=load('readingPageRect','readerViewportMetrics');
const metrics=load('readerViewportMetrics','currentReadingViewport');
const before=pageRect({left:60,top:100,width:170,height:24},{left:-40,top:-900});
const panned=pageRect({left:10,top:60,width:170,height:24},{left:-90,top:-940});
assert.equal(before.left,panned.left);assert.equal(before.top,panned.top);assert.equal(before.width,panned.width);
const viewport=metrics({pageTop:1200,pageLeft:140,height:400,width:350,scale:2,offsetTop:300,offsetLeft:100},{pageTop:900,pageLeft:40,height:800,width:700});
assert.equal(viewport.pageTop,1200);assert.equal(viewport.height,400);assert.equal(viewport.width,350);
const fallback=metrics(undefined,{pageTop:900,pageLeft:40,height:800,width:700});assert.equal(fallback.pageTop,900);assert.equal(fallback.height,800);
console.log('Passed: zoom/pan coordinate invariance, visual viewport sizing and fallback metrics.');
const dotStart=source.indexOf('function scrollDotMetrics(');
const dotEnd=source.indexOf('\nfunction scrollArrowTurn(',dotStart);
const dot=vm.runInNewContext('('+source.slice(dotStart,dotEnd)+')');
assert.equal(dot(0,3000,1000).y,24);
assert.equal(dot(1000,3000,1000).y,500);
assert.equal(dot(2000,3000,1000).y,976);
assert.equal(dot(-100,3000,1000).progress,0);
assert.equal(dot(4000,3000,1000).progress,1);
assert.equal(dot(0,600,1000).maximum,0);
assert.equal(dot(0,600,1000).progress,0);
assert.equal(dot(0,3000,400).travel,352);
console.log('Passed: scroll-dot start/middle/end, overscroll clamping, short articles and resized viewport geometry.');
const turnStart=source.indexOf('function scrollArrowTurn(');
const turnEnd=source.indexOf('\nlet scrollArrowAngle=',turnStart);
const turn=vm.runInNewContext('('+source.slice(turnStart,turnEnd)+')');
assert.equal(turn(90,1,40).angle,90);
const up=turn(90,1,-40);assert.equal(up.angle,270);assert.equal(up.direction,-1);
assert.equal(turn(up.angle,up.direction,-20).angle,270);
const down=turn(up.angle,up.direction,40);assert.equal(down.angle,450);assert.equal(down.direction,1);
assert.equal(turn(down.angle,down.direction,.2).angle,450);
assert.equal(turn(down.angle,down.direction,-.2).direction,1);
console.log('Passed: directional arrow half-turns, continued scrolling and subpixel jitter.');
const ambient=load('ambientViewportMetrics','createAmbientRenderer');
const normal=ambient({width:1200,height:800,scale:1},1200,800,2);
const pinch=ambient({width:300,height:200,scale:4,offsetLeft:160,offsetTop:90},1200,800,2);
assert.equal(normal.width*normal.density,pinch.width*pinch.density);
assert.equal(normal.height*normal.density,pinch.height*pinch.density);
assert.equal(pinch.left,160);assert.equal(pinch.top,90);
const pageZoom=ambient(undefined,300,200,8);
assert.equal(pageZoom.width*pageZoom.density,normal.width*normal.density);
assert.equal(ambient(undefined,1200,800,2).density,2);
assert.equal(ambient({scale:0,width:0,height:0},1200,800,2).width,1200);
console.log('Passed: native-resolution gradient canvas across page/pinch zoom and viewport panning.');
